"""Generate the paper's tables from the reference implementation.

Writes LaTeX tabulars into --out (default build/tables/):
  parameters-cuts.tex, parameters-cuts-c.tex   the parameter sets, from
      parameter_sets.py, with lambda_2 from lambda2_bounds.json
  toy-*.tex   the paper's worked-encoding appendix: counting tables, the
      unranking of one rank, and what a signature reveals
Every number comes from the code; the files must not be edited by hand.

Usage, from the repository root:
    PYTHONPATH=scripts python scripts/paper_tables/make_tables.py
    PYTHONPATH=scripts python scripts/paper_tables/make_tables.py --out DIR
"""

from __future__ import annotations

import argparse
import json
import math
from pathlib import Path

from paper_tables import comparison as cmp
from paper_tables import hash_counts
from paper_tables.parameter_sets import PARAMETER_SETS, ParameterSet

from cuts import CUTS, CUTSParams
from cuts.scheme import decoration_counts, frontier_counts

TABLES = Path(__file__).parents[2] / "build" / "tables"
FILES = {"CUTS": "parameters-cuts.tex", "CUTS+C": "parameters-cuts-c.tex"}
HASH_FILE = "hash-counts.tex"
HASH_MACROS = "hash-counts-macros.tex"
COMPARISON_FILE = "comparison.tex"
MACROS_FILE = "comparison-macros.tex"
HEADER = "% Generated by scripts/paper_tables/make_tables.py. Do not edit.\n"
BOUNDS = Path(__file__).with_name("lambda2_bounds.json")


def proven_lambda2(name: str) -> float:
    """The proven lambda_2 lower bound for a set, from lambda2_bound.py."""
    return json.loads(BOUNDS.read_text())[name]["lambda2"]


def grouped(n: int) -> str:
    """Thousands separated by thin spaces: 327671 -> 327\\,671."""
    return f"{n:,}".replace(",", "\\,")


def cells(p: ParameterSet) -> list[str]:
    x, scheme = p.params, CUTS(p.params)
    label = p.name.removeprefix("cuts-c-").removeprefix("cuts-")
    row = [label, str(x.n), str(x.h), str(x.w), str(x.L), str(x.S)]
    if x.counter_bits:
        row += [str(x.index_bits), str(x.counter_bits)]
    row += [
        grouped(x.signature_bytes),
        grouped(x.verification_hashes),
        grouped(x.keygen_hashes),
        f"{scheme.selector_entropy_bits:.1f}",
    ]
    if x.counter_bits:
        row.append(f"{math.floor(scheme.grinding_bits * 10) / 10:.1f}")  # down
    return [*row, f"{proven_lambda2(p.name):.1f}"]


def render(scheme: str) -> str:
    sets = [p for p in PARAMETER_SETS if p.scheme == scheme]
    head = ["Set", "$n$", "$h$", "$w$", "$L$", "$S$"]
    if scheme == "CUTS+C":
        head += ["$r$", "$s$"]
    head += ["$|\\sigma|$ (B)", "$V$", "$G$", "$\\log_2 M$"]
    if scheme == "CUTS+C":
        head.append("$g$")
    head.append("$\\lambda_2$")
    lines = [
        HEADER,
        # Full text width with the columns spread, so the CUTS and CUTS+C
        # tables have the same width.
        "\\begin{tabular*}{\\linewidth}{@{\\extracolsep{\\fill}}l"
        + "r" * (len(head) - 1)
        + "@{}}\n",
        "\\toprule\n",
        " & ".join(head) + " \\\\\n",
        "\\midrule\n",
    ]
    for i, p in enumerate(sets):
        if i and p.target_bits != sets[i - 1].target_bits:
            lines.append("\\addlinespace\n")
        lines.append(" & ".join(cells(p)) + " \\\\\n")
    lines += ["\\bottomrule\n", "\\end{tabular*}\n"]
    return "".join(lines)


def hash_cells(p: ParameterSet) -> list[str]:
    costs = hash_counts.measure(p.params)
    row = [p.name]
    for cost in (costs.keygen, costs.sign, costs.verify):
        row += [
            grouped(hash_counts.rounded(cost.shake256)),
            grouped(hash_counts.rounded(cost.sha256)),
        ]
    return row


def render_hash_counts() -> str:
    """SHAKE256 permutations and SHA-256 compressions for every set."""
    lines = [
        HEADER,
        "\\begin{tabular}{lrrrrrr}\n",
        "\\toprule\n",
        (
            " & \\multicolumn{2}{c}{KeyGen} & \\multicolumn{2}{c}{Sign}"
            " & \\multicolumn{2}{c}{Verify} \\\\\n"
        ),
        "\\cmidrule(lr){2-3}\\cmidrule(lr){4-5}\\cmidrule(lr){6-7}\n",
        "Set" + " & SHAKE256 & SHA-256" * 3 + " \\\\\n",
        "\\midrule\n",
    ]
    for i, p in enumerate(PARAMETER_SETS):
        if i and p.scheme != PARAMETER_SETS[i - 1].scheme:
            lines.append("\\addlinespace\n")
        lines.append(" & ".join(hash_cells(p)) + " \\\\\n")
    lines += ["\\bottomrule\n", "\\end{tabular}\n"]
    return "".join(lines)


def floor1(v: float) -> str:
    """Rounded down to 0.1, as in the parameter tables."""
    return f"{math.floor(v * 10) / 10:.1f}"


def set_row(p: ParameterSet) -> cmp.Row:
    x, scheme = p.params, CUTS(p.params)
    return cmp.Row(
        p.scheme,
        p.name,
        x.signature_bytes,
        x.verification_hashes,
        x.keygen_hashes,
        scheme.selector_entropy_bits,
        proven_lambda2(p.name),
        scheme.grinding_bits if x.counter_bits else None,
    )


def comparison_rows() -> list[cmp.Row]:
    """WOTS+C, two FORS instances, then every parameter set."""
    max_keygen = max(p.params.keygen_hashes for p in PARAMETER_SETS)
    k, a = cmp.smallest_fors(128, max_keygen)
    return [
        cmp.wots_c_row(),
        cmp.fors_row("SLH-DSA-128s", *cmp.FORS_128S),
        cmp.fors_row(f"$k={k}$, $a={a}$", k, a),
        *(set_row(p) for p in PARAMETER_SETS),
    ]


def render_comparison() -> str:
    head = ["Scheme", "Set", "$|\\sigma|$ (B)", "$V$", "$G$"]
    head += ["$\\lambda_1$", "$\\lambda_2$", "$g$"]
    lines = [
        HEADER,
        "\\begin{tabular}{llrrrrrr}\n",
        "\\toprule\n",
        " & ".join(head) + " \\\\\n",
        "\\midrule\n",
    ]
    rows = comparison_rows()
    for i, r in enumerate(rows):
        if i and r.scheme != rows[i - 1].scheme:
            lines.append("\\addlinespace\n")
        name = r.name.removeprefix("cuts-c-").removeprefix("cuts-")
        cells = [r.scheme, name, grouped(r.bytes), grouped(r.verify)]
        # lambda_1 as log2 M is printed in the parameter tables; lambda_2, g down.
        cells += [grouped(r.keygen), f"{r.lambda1:.1f}", floor1(r.lambda2)]
        cells.append("--" if r.grinding is None else floor1(r.grinding))
        lines.append(" & ".join(cells) + " \\\\\n")
    lines += ["\\bottomrule\n", "\\end{tabular}\n"]
    return "".join(lines)


def span(values) -> str:
    """'52' or '52--53' for a set of integers."""
    lo, hi = min(values), max(values)
    return f"{lo}" if lo == hi else f"{lo}--{hi}"


def render_hash_macros() -> str:
    """Numbers the midstate sentence quotes: prefix bytes, cached share in %."""
    lines = [HEADER]
    for scheme, tag in (("CUTS", "Cuts"), ("CUTS+C", "CutsC")):
        sets = [p for p in PARAMETER_SETS if p.scheme == scheme]
        prefix = [b for p in sets for b in hash_counts.tree_prefix_bytes(p.params)]
        shares = []
        for p in sets:
            c = hash_counts.measure(p.params)
            for cost in (c.keygen, c.sign, c.verify):
                shares.append(round(100 * cost.sha256_cached / cost.sha256))
        lines.append(f"\\newcommand{{\\hcPrefix{tag}}}{{{span(prefix)}}}\n")
        lines.append(f"\\newcommand{{\\hcCached{tag}}}{{{span(shares)}}}\n")
    return "".join(lines)


def render_macros() -> str:
    """Numbers the comparison's text quotes, so none is typed by hand."""
    rows = {r.name: r for r in comparison_rows()}
    w, c = rows["SHRINCS"], rows["cuts-c-48-cheap"]
    values = {
        "WotsBytes": grouped(w.bytes),
        "WotsV": grouped(w.verify),
        "WotsG": grouped(w.keygen),
        "WotsLambdaTwo": floor1(w.lambda2),
        "WotsGrind": floor1(w.grinding),
        "CheapBytes": grouped(c.bytes),
        "CheapV": grouped(c.verify),
        "CheapG": grouped(c.keygen),
        "CheapLambdaTwo": floor1(c.lambda2),
        "CheapGrind": floor1(c.grinding),
    }
    lines = [HEADER]
    lines += [f"\\newcommand{{\\cmp{k}}}{{{v}}}\n" for k, v in values.items()]
    return "".join(lines)


# ---- The worked encoding ------------------------------------------------------

TOY = CUTSParams(16, 2, 3, 3, 2)  # (n, h, w, L, S)
TOY_RANK = 9


def tabular(head: list[str], rows: list[list[str]], align: str) -> str:
    lines = [HEADER, f"\\begin{{tabular}}{{{align}}}\n", "\\toprule\n"]
    lines.append(" & ".join(head) + " \\\\\n")
    lines.append("\\midrule\n")
    lines += [" & ".join(r) + " \\\\\n" for r in rows]
    lines += ["\\bottomrule\n", "\\end{tabular}\n"]
    return "".join(lines)


def render_toy_frontier_counts() -> str:
    """N[t, l]: frontiers of size l in a height-t binary tree."""
    N = frontier_counts(TOY.h, TOY.L)
    head = ["$t$"] + [f"$\\ell={l}$" for l in range(1, TOY.L + 1)]
    rows = [
        [str(t)] + [str(N[t][l]) for l in range(1, TOY.L + 1)] for t in range(TOY.h + 1)
    ]
    return tabular(head, rows, "c" + "r" * TOY.L)


def render_toy_decoration_counts() -> str:
    """D_w[k, s]: position vectors of length k with sum s."""
    D = decoration_counts(TOY.w, TOY.L, TOY.S)
    head = ["$k$"] + [f"$s={s}$" for s in range(TOY.S + 1)]
    rows = [
        [str(k)] + [str(D[k][s]) for s in range(TOY.S + 1)] for k in range(TOY.L + 1)
    ]
    return tabular(head, rows, "c" + "r" * (TOY.S + 1))


def unranking_trace() -> tuple[list[list[str]], tuple[int, ...], tuple[int, ...]]:
    """Unrank TOY_RANK step by step, as in the paper, recording each call."""
    h, w, L, S = TOY.h, TOY.w, TOY.L, TOY.S
    N = frontier_counts(h, L)
    D = decoration_counts(w, L, S)
    rows: list[list[str]] = []
    rk_f, rk_a = divmod(TOY_RANK, D[L][S])
    rows.append(
        [
            f"$\\operatorname{{divmod}}({TOY_RANK},D_{w}[{L},{S}]={D[L][S]})$",
            "",
            f"$(\\mathit{{rk}}_F,\\mathit{{rk}}_A)=({rk_f},{rk_a})$",
        ]
    )

    def frontier(v: int, t: int, size: int, rk: int) -> tuple[int, ...]:
        call = f"$\\UF({v},{t},{size},{rk})$"
        if size == 1:
            rows.append([call, "", f"stop at node ${v}$"])
            return (v,)
        half = 1 << (t - 1)
        skipped: list[str] = []
        for a in range(max(1, size - half), min(half, size - 1) + 1):
            block = N[t - 1][a] * N[t - 1][size - a]
            if rk < block:
                rk_l, rk_r = divmod(rk, N[t - 1][size - a])
                rows.append(
                    [
                        call,
                        ", ".join(skipped + [f"$a={a}$: {block}"]),
                        f"split $a={a}$, ranks $({rk_l},{rk_r})$",
                    ]
                )
                return frontier(2 * v, t - 1, a, rk_l) + frontier(
                    2 * v + 1, t - 1, size - a, rk_r
                )
            skipped.append(f"$a={a}$: {block}")
            rk -= block
        raise AssertionError("unreachable for a valid rank")

    def decoration(k: int, s: int, rk: int) -> tuple[int, ...]:
        if k == 0:
            return ()
        call = f"$\\UD({k},{s},{rk})$"
        tried: list[str] = []
        for a in range(max(0, s - (k - 1) * (w - 1)), min(w - 1, s) + 1):
            block = D[k - 1][s - a]
            tried.append(f"$a={a}$: {block}")
            if rk < block:
                rows.append([call, ", ".join(tried), f"position ${a}$"])
                return (a, *decoration(k - 1, s - a, rk))
            rk -= block
        raise AssertionError("unreachable for a valid rank")

    F = frontier(1, h, L, rk_f)
    A = decoration(L, S, rk_a)
    assert (F, A) == CUTS(TOY).unrank(TOY_RANK), "trace disagrees with scheme.py"
    return rows, F, A


def render_toy_unranking() -> str:
    rows, _, _ = unranking_trace()
    return tabular(
        ["Call", "Blocks (left size or position: count)", "Result"], rows, "lll"
    )


def render_toy_disclosure() -> str:
    """What the signature reveals, and what verification computes from it."""
    _, F, A = unranking_trace()
    w = TOY.w
    revealed = dict(zip(F, A, strict=True))
    rows: list[list[str]] = []
    total = 0

    def recover(v: int) -> None:
        nonlocal total
        if v in revealed:
            a = revealed[v]
            steps = w - 1 - a
            rows.append(
                [
                    f"${v}$",
                    f"revealed $X_{{{v},{a}}}$",
                    f"$X_{{{v},{w - 1}}}$",
                    str(steps),
                ]
            )
            total += steps
            return
        recover(2 * v)
        recover(2 * v + 1)
        merged = f"merge of ${2 * v}$ and ${2 * v + 1}$"
        if v == 1:
            rows.append(["$1$", merged, "$\\pk$", "1"])
            total += 1
            return
        rows.append(
            [
                f"${v}$",
                merged,
                f"$X_{{{v},0}}$, then $X_{{{v},{w - 1}}}$",
                f"{1 + (w - 1)}",
            ]
        )
        total += 1 + (w - 1)

    recover(1)
    assert total == TOY.verification_hashes, "verification count disagrees"
    rows.append(["", "", "Total", str(total)])
    return tabular(["Node", "From", "Computes", "Tree calls"], rows, "clll")


TOY_FILES = {
    "toy-frontier-counts.tex": render_toy_frontier_counts,
    "toy-decoration-counts.tex": render_toy_decoration_counts,
    "toy-unranking.tex": render_toy_unranking,
    "toy-disclosure.tex": render_toy_disclosure,
}


def outputs() -> dict[str, str]:
    """Every generated file, by name, and its contents."""
    files = {name: render(scheme) for scheme, name in FILES.items()}
    files[HASH_FILE] = render_hash_counts()
    files[HASH_MACROS] = render_hash_macros()
    files[COMPARISON_FILE] = render_comparison()
    files[MACROS_FILE] = render_macros()
    files.update({name: fn() for name, fn in TOY_FILES.items()})
    return files


def main(argv=None) -> None:
    p = argparse.ArgumentParser(description=(__doc__ or "").split("\n\n")[0])
    p.add_argument(
        "--out", type=Path, default=TABLES, help="directory to write the tables to"
    )
    args = p.parse_args(argv)
    args.out.mkdir(parents=True, exist_ok=True)
    for name, text in outputs().items():
        path = args.out / name
        path.write_text(text)
        print(f"Wrote {path}")


if __name__ == "__main__":
    main()
